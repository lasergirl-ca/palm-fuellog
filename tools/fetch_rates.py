#!/usr/bin/env python3
"""Fetch the current exchange rates and write them as the app's built-in defaults.

usage: fetch_rates.py src/rates_default.h

The currency order is read from src/currency.h (`#define curXXX n`), so a new
currency there is picked up here without edits. Rates come from the ECB via
api.frankfurter.app (no key) as units per 1 USD, scaled by 1e6. The app derives
"home units per unit of currency" from this table at run time, whatever the home
currency is. If the fetch fails and the header already exists, it is kept and the
build goes on with the previous day's table.
"""
import json, os, re, sys, urllib.request, datetime

out = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "..", "src", "currency.h")).read()
codes = [None] * 16
for m in re.finditer(r"#define cur([A-Z]{3})\s+(\d+)", src):
    codes[int(m.group(2))] = m.group(1)
codes = [c for c in codes if c]
count = int(re.search(r"#define curCount\s+(\d+)", src).group(1))
assert len(codes) == count, (codes, count)

others = ",".join(c for c in codes if c != "USD")
url = "https://api.frankfurter.app/latest?from=USD&to=" + others
try:
    with urllib.request.urlopen(url, timeout=10) as r:
        data = json.load(r)
    rates = data["rates"]; rates["USD"] = 1.0
    date = data["date"]
    per_usd = [int(round(rates[c] * 1e6)) for c in codes]
except Exception as e:   # offline, or the service is down
    if os.path.exists(out):
        old = re.search(r'kRatesDate "([^"]+)"', open(out).read())
        print("fetch_rates: %s; keeping the built-in rates of %s" % (e, old.group(1) if old else "unknown date"))
        sys.exit(0)
    print("fetch_rates: %s and no %s to fall back on" % (e, out)); sys.exit(1)

text = "/* Generated by tools/fetch_rates.py: ECB reference rates of %s via api.frankfurter.app.\n" % date
text += " * Units of each currency per 1 USD, x 1e6, in currency.h order (%s). */\n" % ", ".join(codes)
text += "#ifndef RATES_DEFAULT_H\n#define RATES_DEFAULT_H\n"
text += '#define kRatesDate "%s"\n' % date
text += "#define kRatesPerUsd { %s }\n" % ", ".join("%dUL" % v for v in per_usd)
text += "#endif\n"
if os.path.exists(out) and open(out).read() == text:
    print("fetch_rates: rates of %s unchanged" % date)
else:
    open(out, "w").write(text)
    print("fetch_rates: built-in rates now those of %s: %s" % (date, ", ".join("%s %.4f" % (c, v / 1e6) for c, v in zip(codes, per_usd))))
